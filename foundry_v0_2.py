
#!/usr/bin/env python3
# Foundry v0.2 - Complete Repository Generator

import os
import yaml
import requests
import sys
import subprocess
import time
import re
import json

print("Starting Foundry Repository Generator v0.2")

try:
    # Read the spec.yaml file
    with open("spec.yaml", "r") as f:
        full_content = f.read()
    
    # Print the first few lines for debugging
    print(f"First 50 chars of spec.yaml: {full_content[:50]}")
    
    # Remove "yaml" prefix if present
    lines = full_content.split("\n")
    if lines[0].strip().lower() == "yaml":
        full_content = "\n".join(lines[1:])
        print("Removed 'yaml' header line")
    
    # Split content into config and K8s parts
    parts = full_content.split("---")
    config_text = parts[0].strip()
    k8s_parts = ["---" + part for part in parts[1:] if part.strip()]
    
    # Parse configuration
    config = yaml.safe_load(config_text)
    print(f"Parsed config: {json.dumps(config, indent=2)}")
    
    # Extract key info
    project_name = config.get("project_name", "gravel9-tilt")
    folders = config.get("folders", [])
    files = config.get("files", [])
    options = config.get("options", {})
    
    # Extract additional repo structures if available
    repo_structure = config.get("repo_structure", {})
    source_files = repo_structure.get("source_files", [])
    config_files = repo_structure.get("config_files", [])
    test_files = repo_structure.get("test_files", [])
    
    print(f"Project name: {project_name}")
    print(f"Folders to create: {folders}")
    print(f"Files to create: {files}")
    print(f"Source files: {source_files}")
    print(f"Config files: {config_files}")
    print(f"Test files: {test_files}")
    
    # Get GitHub credentials
    token = os.environ.get("FOUNDRY_TOKEN_PERSONAL")
    username = os.environ.get("FOUNDRY_USERNAME")
    
    if not token or not username:
        print("Missing GitHub credentials")
        sys.exit(1)
    
    # Security check
    if username != "darbybailey":
        print("Unauthorized user")
        sys.exit(1)
    
    # Set author username for proper attribution
    author_username = "darby-foundry"
    
    # Check for existing repository and delete if needed
    print(f"Checking for existing repository: {project_name}")
    check_url = f"https://api.github.com/repos/{username}/{project_name}"
    headers = {
        "Authorization": f"token {token}",
        "Accept": "application/vnd.github.v3+json"
    }
    
    check_res = requests.get(check_url, headers=headers)
    if check_res.status_code == 200:
        print(f"Repository exists - deleting first")
        delete_res = requests.delete(check_url, headers=headers)
        if delete_res.status_code != 204:
            print(f"Failed to delete existing repo: {delete_res.status_code} - {delete_res.text}")
            sys.exit(1)
        print(f"Existing repository deleted successfully")
        
        # Wait for GitHub to process the deletion
        print("Waiting for GitHub to process deletion...")
        time.sleep(3)
    else:
        print("No existing repository found, proceeding with creation")
    
    # Create GitHub repository
    print(f"Creating new GitHub repository: {project_name}")
    create_url = "https://api.github.com/user/repos"
    create_data = {
        "name": project_name,
        "private": options.get("visibility", "public") != "public",
        "auto_init": False,
        "description": options.get("description", f"Repository generated by Foundry for {project_name}")
    }
    
    create_res = requests.post(create_url, headers=headers, json=create_data)
    
    if create_res.status_code != 201:
        print(f"Failed to create GitHub repository: {create_res.status_code} - {create_res.text}")
        sys.exit(1)
    
    repo_url = create_res.json().get('html_url')
    print(f"GitHub repository created: {repo_url}")
    
    # Wait for GitHub to set up the repository
    print("Waiting for GitHub to set up the repository...")
    time.sleep(2)
    
    # Clean up any existing directory
    if os.path.exists(project_name):
        import shutil
        shutil.rmtree(project_name)
        print(f"Removed existing local directory: {project_name}")
    
    # Create project directory
    os.makedirs(project_name, exist_ok=True)
    os.chdir(project_name)
    print(f"Created and entered directory: {project_name}")
    
    # Function to handle nested paths
    def ensure_directory(file_path):
        directory = os.path.dirname(file_path)
        if directory and not os.path.exists(directory):
            os.makedirs(directory, exist_ok=True)
            print(f"Created directory: {directory}")
    
    # Create folders first
    print("Creating folder structure...")
    for folder in folders:
        if isinstance(folder, str) and folder != ".":
            os.makedirs(folder, exist_ok=True)
            print(f"Created folder: {folder}")
    
    # Create standard files
    print("Creating standard files...")
    for file in files:
        if isinstance(file, str):
            if file == f"{project_name}-deployment.yaml" or file == "gravel9-tilt-deployment.yaml":
                # Create deployment file with full Kubernetes content
                ensure_directory(file)
                with open(file, "w") as f:
                    for part in k8s_parts:
                        f.write(part + "\n")
                print(f"Created deployment file: {file} ({os.path.getsize(file)} bytes)")
            elif file == "README.md":
                ensure_directory(file)
                with open(file, "w") as f:
                    f.write(f"# {project_name}\n\n")
                    f.write("Resonant node for veiled patterns and sovereign memory.\n\n")
                    f.write("## Components\n\n")
                    f.write("- Quantum Veil\n")
                    f.write("- Pattern Oracle\n")
                    f.write("- Memory Totem\n")
                    f.write("- Flywheel Controller\n")
                    f.write("- Symbolic Signal UI\n")
                print(f"Created README file: {file}")
            else:
                ensure_directory(file)
                with open(file, "w") as f:
                    pass
                print(f"Created empty file: {file}")
    
    # Create source files
    print("Creating source files...")
    for source_file in source_files:
        if isinstance(source_file, dict):
            file_path = source_file.get('path', '')
            content = source_file.get('content', '')
            
            if file_path:
                ensure_directory(file_path)
                with open(file_path, "w") as f:
                    f.write(content)
                print(f"Created source file: {file_path}")
    
    # Create config files
    print("Creating config files...")
    for config_file in config_files:
        if isinstance(config_file, dict):
            file_path = config_file.get('path', '')
            content = config_file.get('content', '')
            
            if file_path:
                ensure_directory(file_path)
                with open(file_path, "w") as f:
                    f.write(content)
                print(f"Created config file: {file_path}")
    
    # Create test files
    print("Creating test files...")
    for test_file in test_files:
        if isinstance(test_file, dict):
            file_path = test_file.get('path', '')
            content = test_file.get('content', '')
            
            if file_path:
                ensure_directory(file_path)
                with open(file_path, "w") as f:
                    f.write(content)
                print(f"Created test file: {file_path}")
    
    # Process any additional repository structure
    # Add more sections here based on your spec.yaml structure
    
    # Print summary of created files
    file_count = len(os.popen('find . -type f | wc -l').read().strip())
    dir_count = len(os.popen('find . -type d | wc -l').read().strip())
    print(f"Repository created with {file_count} files and {dir_count} directories")
    
    # Initialize git repository
    print("Initializing git repository")
    subprocess.run(["git", "init"], check=True)
    
    # Set git user to darby-foundry for proper attribution
    subprocess.run(["git", "config", "user.name", author_username], check=True)
    subprocess.run(["git", "config", "user.email", "foundry@example.com"], check=True)
    
    # Add and commit files
    print("Adding files to git")
    subprocess.run(["git", "add", "."], check=True)
    print("Committing files")
    subprocess.run(["git", "commit", "-m", "Initial commit from Foundry"], check=True)
    
    # Push to GitHub
    remote_url = f"https://{username}:{token}@github.com/{username}/{project_name}.git"
    print(f"Adding git remote")
    subprocess.run(["git", "remote", "add", "origin", remote_url], check=True)
    
    # Push using main branch
    print("Pushing to main branch")
    subprocess.run(["git", "branch", "-M", "main"], check=True)
    
    try:
        push_result = subprocess.run(["git", "push", "-u", "origin", "main"], 
                                  check=True, capture_output=True, text=True)
        print("Push successful")
    except subprocess.CalledProcessError as e:
        print(f"Push error: {e.stderr}")
        sys.exit(1)
    
    print(f"Repository creation complete: https://github.com/{username}/{project_name}")
    
except Exception as e:
    print(f"Error: {e}")
    import traceback
    traceback.print_exc()
    sys.exit(1)
